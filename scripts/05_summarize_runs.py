"""Collects runs/*/metrics.json and runs/*/gen_*.json into reports/baseline_results.md.
Reports mean ± standard deviation over seeds for every configuration."""
import collections, glob, json, os, re, statistics

ROOT = os.path.join(os.path.dirname(__file__), "..")
runs = collections.defaultdict(list)        # config label -> [(metrics, {scenario: gen json})]
refs = {}                                   # (scenario, representation) -> reference metrics
for f in sorted(glob.glob(os.path.join(ROOT, "runs", "*", "metrics.json"))):
    m = json.load(open(f)); c = m["config"]; d = os.path.dirname(f)
    if c.get("smoke") or m["name"].startswith("sanity"): continue
    gens = {}
    for g in glob.glob(os.path.join(d, "gen_*.json")):
        j = json.load(open(g)); tag = os.path.basename(g)[:-5]; gens[tag] = j["generated"]
        base = tag.replace("_constrained", "")
        if c["pitch"] in ("koma53", "koma53_rel"): refs[(base, "53-comma")] = j["reference"]
        if c["pitch"] == "tet12": refs[(base, "12-TET")] = j["reference"]
    runs[re.sub(r"-s\d+$", "", m["name"])].append((m, gens))

def ms(vals, pct=False):
    vals = [v for v in vals if v is not None]
    if not vals: return "–"
    k = 100 if pct else 1; f = "{:.1f}%" if pct else "{:.3f}"
    out = f.format(statistics.mean(vals) * k)
    return out + (" ± " + f.format(statistics.stdev(vals) * k) if len(vals) > 1 else "")

def label(c):
    extra = []
    if c.get("pos"): extra.append("POS tokens")
    if c["model"] == "transformer" and (c["layers"], c["d_model"]) != (6, 256): extra.append(f"{c['layers']}L d{c['d_model']}")
    if c["dropout"] != 0.1: extra.append(f"dropout {c['dropout']}")
    return f"| {c['model']} | {c['pitch']} | {c['cond']} | {', '.join(extra) or '–'} |"

L = ["# Baseline results\n", "Generated by `scripts/05_summarize_runs.py`. Mean ± standard deviation over seeds.\n",
     "## Held-out likelihood\n",
     "Bits per note are comparable across encodings; per-token perplexity is not. `tet12` predicts a coarser pitch target. "
     "The few-shot pool holds makams that never occur in training (zero-shot); its UNK column is the share of target tokens outside the vocabulary.\n",
     "| Model | Pitch | Cond | Variant | Seeds | Params | Best step | Test bits/note | pitch | duration | Few-shot bits/note | Few-shot UNK |",
     "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for k in sorted(runs):
    r = [m for m, _ in runs[k]]; t = lambda key: ms([x["test"][key] for x in r])
    fs = [x.get("few_shot") for x in r]
    best = [min(x["history"], key=lambda h: h["nll_per_token"])["step"] for x in r]
    L.append(f"{label(r[0]['config'])} {len(r)} | {r[0]['n_params'] / 1e6:.2f}M | {round(statistics.mean(best))} | {t('bits_per_note')} | "
             f"{t('pitch_bits_per_note')} | {t('dur_bits_per_note')} | {ms([x['bits_per_note'] for x in fs if x])} | "
             f"{ms([x['unk_rate'] for x in fs if x], pct=True)} |")

def gen_table(title, note, base, cols):
    rows = []
    for k in sorted(runs):
        for tag, dec in ((base, "free"), (base + "_constrained", "constrained")):
            g = [x[tag] for _, x in runs[k] if tag in x]
            if g: rows.append(f"{label(runs[k][0][0]['config'])} {dec} | " + " | ".join(ms([x.get(q) for x in g], pct=p) for q, _, p in cols) + " |")
    if not rows: return
    L.extend([f"\n## {title}\n", note + "\n",
              "| Model | Pitch | Cond | Variant | Decoding | " + " | ".join(h for _, h, _ in cols) + " |", "|---|---|---|---|---|" + "---|" * len(cols)])
    L.extend(rows)
    for rep in ("53-comma", "12-TET"):
        ref = refs.get((base, rep))
        if ref: L.append(f"| *real music ({rep})* | | | | | " + " | ".join(ms([ref.get(q)], pct=p) for q, _, p in cols) + " |")

common = [("scale_overlap", "Scale overlap ↑", False), ("off_scale_rate", "Off-scale ↓", True), ("bar_validity", "Valid measures ↑", True),
          ("copy_rate", "Copy rate", True), ("grammar_ok", "Grammar ok ↑", True)]
gen_table("Scenario 1: autocomplete", "The model continues a test piece from its first 16 notes for 64 notes.", "gen_prompt16", common)
gen_table("Scenario 2: composition from scratch", "Only makam, usul and form are given; the model writes until it ends the piece itself.",
          "gen_prompt0_full", common + [("ends_on_karar", "Ends on karar ↑", True), ("eos_rate", "Ended by model", True), ("mean_notes", "Mean notes", False)])
open(os.path.join(ROOT, "reports", "baseline_results.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L))
