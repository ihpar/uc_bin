"""SymbTr v3 data report: distributions, vocabulary sizes, piece-level stratified split.
Run: python scripts/01_data_report.py"""
import os, sys, collections, statistics, random, csv
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from src.symbtr import iter_pieces, REST
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = os.path.join(os.path.dirname(__file__), "..")
MIN_PIECES = 20          # minimum pieces per makam for full evaluation
SEED = 13

pieces = []
mk, us, fm = collections.Counter(), collections.Counter(), collections.Counter()
pitch, dur, kod = collections.Counter(), collections.Counter(), collections.Counter()
notes_mk = collections.Counter()
finalis = collections.defaultdict(collections.Counter)
for p in iter_pieces():
    ns = p.notes
    sounded = [n for n in ns if n[0] != REST]
    for r in p.rows: kod[r["Kod"]] += 1
    for n in sounded: pitch[n[0]] += 1
    for n in ns: dur[(n[1], n[2])] += 1
    m = p.meta
    mk[m["makam"]] += 1; us[m["usul"]] += 1; fm[m["form"]] += 1
    notes_mk[m["makam"]] += len(sounded)
    if sounded: finalis[m["makam"]][sounded[-1][0]] += 1
    pieces.append(dict(fname=p.fname, **m, n_note=len(sounded), n_rest=len(ns) - len(sounded),
                       n_row=len(p.rows)))

N = len(pieces); tot = sum(x["n_note"] for x in pieces)
lens = sorted(x["n_note"] for x in pieces)

# --- piece-level split: files sharing title + composer stay in the same set (leakage guard)
big = {m for m, c in mk.items() if c >= MIN_PIECES}
groups = collections.defaultdict(list)
for x in pieces:
    key = (x["title"], x["composer"]) if x["title"] else (x["fname"],)
    groups[key].append(x)
rng = random.Random(SEED)
by_mk = collections.defaultdict(list)
for key, g in groups.items():
    by_mk[g[0]["makam"]].append(g)
for m, gl in by_mk.items():
    rng.shuffle(gl)
    n = len(gl)
    for i, g in enumerate(gl):
        if m not in big: s = "few_shot"
        elif i < round(0.8 * n): s = "train"
        elif i < round(0.9 * n): s = "val"
        else: s = "test"
        for x in g: x["split"] = s
with open(os.path.join(ROOT, "data", "splits.csv"), "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(pieces[0].keys())); w.writeheader(); w.writerows(pieces)
split = collections.Counter(x["split"] for x in pieces)
split_notes = collections.Counter()
for x in pieces: split_notes[x["split"]] += x["n_note"]
multi = sum(1 for g in groups.values() if len(g) > 1)

# --- figures
fig, ax = plt.subplots(figsize=(8, 3.2))
vals = sorted(mk.values(), reverse=True)
ax.bar(range(len(vals)), vals, color="#3b6ea5"); ax.set_yscale("log")
ax.axhline(MIN_PIECES, color="#b33", lw=1, ls="--"); ax.text(len(vals) * 0.6, MIN_PIECES * 1.15, f"threshold = {MIN_PIECES} pieces", color="#b33", fontsize=8)
ax.set_xlabel("makam (sorted by number of pieces)"); ax.set_ylabel("pieces (log)")
ax.set_title("SymbTr v3: pieces per makam"); fig.tight_layout()
fig.savefig(os.path.join(ROOT, "reports", "figures", "makam_distribution.png"), dpi=150); plt.close(fig)

fig, ax = plt.subplots(figsize=(8, 3.2))
ax.hist([l for l in lens if l <= 1500], bins=60, color="#3b6ea5")
ax.set_xlabel("sounded notes per piece"); ax.set_ylabel("pieces")
ax.set_title("SymbTr v3: piece lengths (clipped at 1500)"); fig.tight_layout()
fig.savefig(os.path.join(ROOT, "reports", "figures", "piece_lengths.png"), dpi=150); plt.close(fig)

def below(c, t): return sum(1 for v in c.values() if v < t)
def cover(c, t):
    k = [m for m, v in c.items() if v >= t]; return len(k), sum(c[m] for m in k)

L = []
A = L.append
A("# SymbTr v3 data report\n")
A("Generated by `scripts/01_data_report.py`. Numbers are computed from the files in `symbtr_v3/txt_v3`; makam/form/usul labels are taken from the file names.\n")
A("## Overview\n")
A(f"| Measure | Value |\n|---|---|\n| Pieces (files) | {N} |\n| Makam labels | {len(mk)} |\n| Usul labels | {len(us)} |\n| Form labels | {len(fm)} |\n"
  f"| Sounded notes | {tot:,} |\n| Total rows (all Kod values) | {sum(kod.values()):,} |\n"
  f"| Sounded notes per piece (median / mean) | {statistics.median(lens):.0f} / {statistics.mean(lens):.0f} |\n"
  f"| Shortest / longest piece | {lens[0]} / {lens[-1]} |\n"
  f"| Distinct pitches (Koma53) | {len(pitch)} |\n| Distinct durations (Pay/Payda) | {len(dur)} |\n")
A("\n## Makam distribution (long tail)\n")
A("![makam distribution](figures/makam_distribution.png)\n")
A("| Threshold | Makams below threshold |\n|---|---|")
for t in (2, 5, 10, 20, 50): A(f"| < {t} pieces | {below(mk, t)} |")
A("\n| Threshold | Makams | Pieces | Share of pieces |\n|---|---|---|---|")
for t in (10, 20, 50, 100):
    k, c = cover(mk, t); A(f"| ≥ {t} pieces | {k} | {c} | {100 * c / N:.0f}% |")
A(f"\n**Makams with at least {MIN_PIECES} pieces:**\n")
A("| Makam | Pieces | Notes | Most frequent final pitch (Koma53) | Share of pieces ending on it |\n|---|---|---|---|---|")
for m, c in mk.most_common():
    if c < MIN_PIECES: break
    fp, fc = finalis[m].most_common(1)[0]
    A(f"| {m} | {c} | {notes_mk[m]:,} | {fp} | {100 * fc / sum(finalis[m].values()):.0f}% |")
A("\n## Usul and form\n")
A(f"- Usuls with fewer than 5 pieces: {below(us, 5)} of {len(us)}; usuls with at least 20 pieces: {cover(us, 20)[0]} ({100 * cover(us, 20)[1] / N:.0f}% of pieces).")
A("- Most frequent usuls: " + ", ".join(f"{k} ({v})" for k, v in us.most_common(10)) + ".")
A("- Most frequent forms: " + ", ".join(f"{k} ({v})" for k, v in fm.most_common(10)) + ".")
A("\n## Piece lengths\n")
A("![piece lengths](figures/piece_lengths.png)\n")
A("\n## Vocabulary\n")
A(f"- The 20 most frequent duration values cover {100 * sum(v for _, v in dur.most_common(20)) / sum(dur.values()):.1f}% of all notes/rests (out of {len(dur)} distinct values).")
A(f"- Pitch range (Koma53): {min(pitch)}–{max(pitch)}; the 60 most frequent pitches cover {100 * sum(v for _, v in pitch.most_common(60)) / tot:.1f}% of sounded notes.")
A("- Row types (Kod): " + ", ".join(f"{k}: {v:,}" for k, v in kod.most_common(8)) + ".")
A("\n## Piece-level stratified split\n")
A(f"`data/splits.csv` (seed {SEED}). Rule: 80/10/10 within each makam that has at least {MIN_PIECES} pieces; all other makams go to the `few_shot` pool (for few-shot generalisation experiments). Files sharing the same title and composer ({multi} groups) are kept in the same set.\n")
A("| Set | Pieces | Sounded notes |\n|---|---|---|")
for s in ("train", "val", "test", "few_shot"): A(f"| {s} | {split[s]} | {split_notes[s]:,} |")
A("\n## Notes\n")
A("- Files use mixed encodings (UTF-8 and Windows-1254); the parser tries both.")
A("- Label counts from file names do not match the Zenodo record exactly (164 makams, 135 usuls, 61 forms). The difference may come from label variants (e.g. `hicaz_uzzal`, `yuruksemai_4`) and pieces with usul changes; this needs a separate check.")
A("- The txt files hold the performance order with repeats expanded; note-level alignment with the printed score needs the mu2/MusicXML versions.")
open(os.path.join(ROOT, "reports", "data_report.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L[:12]))
